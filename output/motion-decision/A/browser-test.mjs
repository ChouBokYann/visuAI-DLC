import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH});
const target=process.env.ATLAS_URL || 'http://127.0.0.1:17820';
await fs.mkdir('.checks',{recursive:true});
for(const [name,width,height] of [['desktop',1280,860],['phone',390,844]]){
 const page=await browser.newPage({viewport:{width,height},reducedMotion:'no-preference'});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(target);
 await page.waitForSelector('.map-label');
 const view=page.locator('.map-viewport');
 await view.scrollIntoViewIfNeeded();
 const sample=()=>page.evaluate(()=>{const v=document.querySelector('.map-viewport'),c=document.querySelector('.map-canvas'),p=document.querySelector('.route-reveal');return [Math.round(c.offsetWidth/v.clientWidth*100),v.scrollLeft,v.scrollTop,p?parseFloat(getComputedStyle(p).strokeDashoffset):null]});
 const snapshot=async label=>{console.log(name,label,await sample());await view.screenshot({path:'.checks/'+name+'-'+label+'.png',animations:'allow'});};
 await snapshot('overview');
 await page.getByRole('button',{name:'Explore Guatemala',exact:true}).click();
 await page.waitForTimeout(280);await snapshot('approach');assert.ok((await sample())[0]>100);
 await page.waitForTimeout(330);await snapshot('near');
 await page.waitForTimeout(220);await snapshot('drawing');
 await page.waitForTimeout(850);await snapshot('connected');assert.equal((await sample())[3],0);
 assert.match(await page.locator('.journey-ticket a').innerText(),/Nylon Coffee/);
 await page.locator('.origin-list button').filter({hasText:'Indonesia'}).click();
 await page.waitForTimeout(320);
 const start=await sample();
 await page.locator('.origin-list button').filter({hasText:'Ethiopia'}).click();
 const changed=await sample();assert.ok(changed[0]>100);await page.waitForTimeout(1700);
 console.log(name,'retarget before/after/final',start,changed,await sample());
 assert.equal(await page.locator('.origin-name').innerText(),'Ethiopia');
 assert.equal(await page.locator('.journey-ticket a').count(),2);
 await page.locator('.journey-ticket a').first().click();
 assert.match(page.url(),/#cafe-ppp$/);assert.equal(await page.locator('#cafe-ppp h3').innerText(),'PPP Coffee');
 assert.ok(await page.locator('.origin-photo img').evaluate(i=>i.complete&&i.naturalWidth>0));
 await page.getByRole('button',{name:'Add to compare'}).click();await page.getByRole('button',{name:'Compare origins (1/3)'}).click();
 assert.equal(await page.locator('.comparison h3').innerText(),'Ethiopia');await page.getByText('Return to exploration').click();
 await page.getByRole('button',{name:'Reset map zoom'}).click();await page.waitForTimeout(420);assert.deepEqual((await sample()).slice(0,3),[100,0,0]);
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.locator('.origin-list button').filter({hasText:'Kenya'}).click();
 const instant=await sample();await page.waitForTimeout(240);assert.deepEqual(await sample(),instant);
 assert.equal(await page.locator('.route-reveal').evaluate(el=>getComputedStyle(el).animationName),'none');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);await page.close();
}
await browser.close();
