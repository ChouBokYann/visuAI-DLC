import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const root=process.cwd(),base=resolve(root,'experiments/coordinate-agent-work-resilience');
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const read=p=>JSON.parse(readFileSync(resolve(base,p),'utf8').replace(/^\uFEFF/,''));
const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8'}).trim();
const initial=read('records/protected-before.json'),fixture=read('records/fixture-manifest.json'),setup=read('records/setup.json');
const differences=(entries,dir)=>Object.entries(entries).filter(([p,h])=>!existsSync(resolve(dir,p))||hash(resolve(dir,p))!==h).map(([p])=>p);
const historicalChanges=differences(initial.files,root),fixtureChanges=differences(fixture,resolve(base,'fixture'));
const refs={main:git('rev-parse','main'),firstIteration:git('rev-parse','first-iteration')};
const status=git('status','--porcelain','--untracked-files=all');
const outside=status.split('\n').filter(Boolean).filter(line=>!line.slice(3).replace(/^"|"$/g,'').startsWith('experiments/coordinate-agent-work-resilience/'));
const result={at:new Date().toISOString(),historicalFiles:Object.keys(initial.files).length,historicalChanges,fixtureFiles:Object.keys(fixture).length,fixtureChanges,refs,expectedRefs:initial.refs,outsideScopeChanges:outside,skillUnchanged:hash(resolve(root,setup.skillPath))===setup.skillSha256,protocolUnchanged:hash(resolve(base,'README.md'))===setup.protocolSha256};
writeFileSync(resolve(base,'records/isolation-result.json'),JSON.stringify(result,null,2)+'\n');
assert.deepEqual(historicalChanges,[]);assert.deepEqual(fixtureChanges,[]);assert.deepEqual(refs,initial.refs);assert.deepEqual(outside,[]);assert(result.skillUnchanged);assert(result.protocolUnchanged);
console.log(JSON.stringify(result));
