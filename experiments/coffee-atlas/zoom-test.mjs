import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const out=new URL('../../output/coffee-atlas/zoom/',import.meta.url);
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const results=[];
async function selectedPointIsVisible(){
 const bounds=await page.locator('.map-viewport').boundingBox();
 const point=await page.locator('.origin-discovery circle').boundingBox();
 expect(point.x).toBeGreaterThanOrEqual(bounds.x);
 expect(point.y).toBeGreaterThanOrEqual(bounds.y);
 expect(point.x+point.width).toBeLessThanOrEqual(bounds.x+bounds.width);
 expect(point.y+point.height).toBeLessThanOrEqual(bounds.y+bounds.height);
}
try{
 await page.goto(process.env.ATLAS_BASE_URL??'http://127.0.0.1:17821');
 const zoomIn=page.getByRole('button',{name:'Zoom in',exact:true});
 const zoomOut=page.getByRole('button',{name:'Zoom out',exact:true});
 await expect(zoomIn).toBeVisible();
 await expect(zoomOut).toBeDisabled();
 const initial=await page.locator('.map-canvas').boundingBox();
 await zoomIn.focus();await page.keyboard.press('Enter');
 await expect(page.getByRole('status',{name:'Map zoom'})).toHaveText('150%');
 expect((await page.locator('.map-canvas').boundingBox()).width).toBeCloseTo(initial.width*1.5,0);
 await zoomIn.click();await zoomIn.click();
 await expect(zoomIn).toBeDisabled();
 await expect(page.getByRole('status',{name:'Map zoom'})).toHaveText('250%');
 results.push('Keyboard zoom, scale and upper/lower bounds');
 const viewport=page.locator('.map-viewport');
 await viewport.evaluate(el=>{el.scrollLeft=450;el.scrollTop=100;});
 const rect=await viewport.boundingBox();
 await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.85);
 await page.mouse.down();await page.mouse.move(rect.x+rect.width*.5-90,rect.y+rect.height*.85-35,{steps:6});await page.mouse.up();
 expect(await viewport.evaluate(el=>el.scrollLeft)).toBeGreaterThan(500);
 results.push('Mouse drag pans zoomed content');
 await viewport.focus();
 const beforeKey=await viewport.evaluate(el=>el.scrollTop);
 await page.keyboard.press('ArrowDown');
 await expect.poll(()=>viewport.evaluate(el=>el.scrollTop)).toBeGreaterThan(beforeKey);
 results.push('Focused map supports native keyboard panning');
 await page.getByRole('button',{name:'Explore Ethiopia',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Ethiopia',exact:true})).toBeVisible();
 await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{}))));
 await selectedPointIsVisible();
 await page.screenshot({path:fileURLToPath(new URL('desktop-closeup.png',out)),fullPage:true});
 results.push('Zoomed selection retains origin details');
 await page.getByRole('button',{name:'Reset map zoom',exact:true}).click();
 await expect(page.getByRole('status',{name:'Map zoom'})).toHaveText('100%');
 expect(await viewport.evaluate(el=>el.scrollLeft+el.scrollTop)).toBe(0);
 await page.screenshot({path:fileURLToPath(new URL('desktop-overview.png',out)),fullPage:true});
 results.push('Reset restores full map and scroll position');
 await page.setViewportSize({width:390,height:900});
 await zoomIn.click();await zoomIn.click();
 await page.getByRole('button',{name:'Explore Indonesia',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Indonesia',exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await page.evaluate(()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{}))));
 await selectedPointIsVisible();
 await page.evaluate(async()=>{window.scrollTo({top:0,behavior:'instant'});await new Promise(requestAnimationFrame);await new Promise(requestAnimationFrame);});
 await selectedPointIsVisible();
 await page.screenshot({path:fileURLToPath(new URL('mobile-closeup.png',out))});
 results.push('Mobile zoom and selection without page overflow');
 const touchContext=await browser.newContext({viewport:{width:390,height:900},hasTouch:true,isMobile:true});
 try{
  const touchPage=await touchContext.newPage();
  await touchPage.goto(process.env.ATLAS_BASE_URL??'http://127.0.0.1:17821');
  await touchPage.getByRole('button',{name:'Zoom in',exact:true}).tap();
  await touchPage.getByRole('button',{name:'Zoom in',exact:true}).tap();
  const area=touchPage.locator('.map-viewport'),bounds=await area.boundingBox();
  const before=await area.evaluate(el=>el.scrollLeft);
  const cdp=await touchContext.newCDPSession(touchPage);
  const x=bounds.x+bounds.width*.7,y=bounds.y+bounds.height*.85;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  for(let i=1;i<=5;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-i*14,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect.poll(()=>area.evaluate(el=>el.scrollLeft)).toBeGreaterThan(before+20);
  results.push('Chromium touch-emulated swipe pans zoomed map');
 }finally{await touchContext.close();}
 await writeFile(new URL('results.json',out),JSON.stringify({verdict:'pass',results},null,2));
 console.log(`ZOOM VERIFIED: ${results.length} groups`);
}finally{await browser.close();}
