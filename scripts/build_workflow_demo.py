"""Rebuild browser demo projections from the canonical synthetic Markdown."""
import json
from pathlib import Path

from export_workflow import export


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    samples = {name: export(root / 'docs/examples/business-context' / ('baseline-' + name),
                            'cafe-trial', 'synthetic-' + name, True) for name in ('a', 'b')}
    content = json.dumps(samples, ensure_ascii=True, separators=(',', ':'))
    destination = root / 'experiments/project-overview/workflow-samples.js'
    destination.write_text('// Generated by scripts/build_workflow_demo.py; edit source Markdown.\n'
                           '(function(root){const samples=' + content + ';'
                           'if(typeof module!=="undefined")module.exports=samples;'
                           'else root.WorkflowSamples=samples;'
                           '})(typeof window==="undefined"?globalThis:window);\n', encoding='utf-8')
    print(destination)
